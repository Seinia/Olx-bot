class OlxError(Exception):
    """Базовое исключение проекта."""


class ConfigError(OlxError):
    """Конфигурация непригодна. Поднимается на старте, процесс не продолжает работу."""


class TransportError(OlxError):
    """Сетевой сбой: таймаут, обрыв, DNS. Лечится ретраем."""


class BlockedError(TransportError):
    """Источник ответил 403 или 429.

    Отделено от TransportError, потому что реакция другая: не просто повторить,
    а увеличить паузу, переключиться на прокси и сообщить владельцу.
    """


class SchemaError(OlxError):
    """Ответ пришёл в неожиданной форме.

    Никогда не подменяется пустым результатом: OLX отдаёт недокументированный
    внутренний API без версионирования, и «ничего не нашлось» неотличимо от
    «структура ответа поменялась». Молчаливая деградация здесь опаснее падения.
    """


class StorageError(OlxError):
    """БД недоступна или заблокирована."""
